"""Текстовые правила, общие с другими сервисами: менять только вместе с ними."""

import re

# Правило ноутбука (ячейки 31, 34), воспроизведённое дословно. Им же db-svc нормализует
# варианты быстрых ответов при импорте, поэтому вопрос обязан нормализоваться так же.
# Диапазон [а-яА-Я] не включает Ё/ё: буква вырезается, «ещё» превращается в «ещ».
_VARIANT_STRIP_RE = re.compile(r"[^a-zA-Zа-яА-Я0-9\s]")


def normalize_variant(text: str) -> str:
    """Нормализация вопроса для поиска быстрых ответов (как у сохранённых вариантов)."""
    return _VARIANT_STRIP_RE.sub("", text).lower().strip()


def chunk_retrieval_text(title: str, category: str, section: str, text: str) -> str:
    """Текст чанка для BM25 (ячейка 13) — тот же, что ingest-worker отправляет на эмбеддинг.

    Префикс `passage: ` здесь не нужен: его ставит embedding-svc, а в BM25 он не участвовал бы
    иначе, чем лишним токеном во всех документах.
    """
    return (
        f"Название документа: {title}\n"
        f"Категория: {category}\n"
        f"Раздел: {section}\n"
        f"Текст: {text}"
    )
