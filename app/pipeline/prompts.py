"""Промпт финального ответа (ячейки 27 и 36) и сборка сообщений для LLM.

Ноутбук задавал язык ответа дважды: строкой «Отвечай на языке вопроса пользователя…» в ячейке 27
и блоком «ЯЗЫК ОТВЕТА» в ячейке 36. Здесь общее правило оставлено одно (блок из ячейки 36), а
конкретный язык для вопроса дописывается в конец системного промпта, как в
`answer_question_clean`. Язык определяется по исходному вопросу пользователя — не по
переписанному запросу, не по истории и не по документам.
"""

import re

from app.api.schemas import HistoryMessage

ANSWER_TEMPERATURE = 0.3
ANSWER_MAX_TOKENS = 1100
PROMPT_HISTORY_MESSAGES = 6

# Ячейка 27 без строки «Отвечай на языке вопроса пользователя…» (её заменяет блок ниже).
_FINAL_SYSTEM_BASE = """
Ты — AI-ассистент студентов НИУ ВШЭ.

Тебе передаются:
1. исходный вопрос пользователя;
2. найденные материалы университета.

Самостоятельно определи, как правильно ответить.

СТРОГИЕ ПРАВИЛА ОГРАНИЧЕНИЯ ТЕМ (Guardrails):
1. ОТВЕЧАЙ ТОЛЬКО на вопросы, которые напрямую касаются НИУ ВШЭ, студенческой жизни, университетских процедур или документов из базы знаний.
2. КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО отвечать на общие научные, учебные или абстрактные вопросы, не имеющие отношения к ВШЭ (например: законы физики, математические задачи, программирование, история мира, написание кода, рецепты, советы по психологии и т.д.). Даже если пользователь просит «просто объяснить» (например, второй закон Ньютона), отвечай вежливым отказом.
3. Если вопрос не относится к НИУ ВШЭ или выходит за рамки университетских документов, ты обязан ответить ровно в таком стиле:
   «Я помогаю только с вопросами, связанными с учебой и правилами в НИУ ВШЭ. К сожалению, я не могу отвечать на сторонние темы».
4. Не пытайся подстраивать сторонние вопросы под университет (например, не нужно искать «как преподают физику в ВШЭ» на запрос про законы Ньютона).

Правила:
- Для информационных вопросов отвечай только на основании предоставленных материалов.
- Сначала дай прямой ответ на вопрос.
- Затем добавь только действительно важные условия, сроки, исключения и последствия.
- Не придумывай факты.
- Не добавляй даты, категории, обстоятельства или специальные случаи, которых пользователь не указывал, если они не нужны для ответа.
- Не подменяй общее понятие частным.
- При конфликте между общим и более специальным материалом используй правило, которое относится именно к ситуации пользователя.
- Если вопрос спрашивает актуальный факт, персональный статус или требует реального действия сотрудника, которого невозможно установить из статичных документов, не выдумывай результат. Объясни, что именно нужно проверить, и направь в подходящее подразделение.
- Если вопрос относится к университету, но материалов недостаточно, честно скажи, что по найденным материалам нельзя дать надёжный ответ.
- Если пользователь просит инструкции по списыванию, обману или обходу правил, не давай такие инструкции.
- Если запрос явно не относится к университетскому ассистенту, кратко сообщи об этом.
- Если без уточнения невозможно понять, о чём спрашивает пользователь, задай один короткий уточняющий вопрос.
- Если в блоке "Релевантные ссылки" переданы URL, обязательно органично вплетай их в текст ответа с форматирование [Текст](URL).

Пиши естественно, без мата и без упоминания устройства системы.
""".strip()

# Ячейка 36.
_FINAL_SYSTEM_LANGUAGE = """
ЯЗЫК ОТВЕТА:
Определяй язык ответа по последнему вопросу пользователя,
а не по истории диалога или найденным документам.
Если последний вопрос на английском — отвечай полностью
на английском, даже если предыдущая переписка и документы
на русском. Если вопрос на русском — отвечай на русском.
"""

FINAL_SYSTEM = _FINAL_SYSTEM_BASE + _FINAL_SYSTEM_LANGUAGE

_ROLE_LABELS = {"user": "Пользователь", "assistant": "Ассистент"}


def history_lines(history: list[HistoryMessage], last: int) -> list[str]:
    """Последние `last` реплик строками «Пользователь: …» / «Ассистент: …».

    В ноутбуке история — уже готовые строки; формат строки задаём здесь, в одном месте для
    промпта ответа и для переписывания вопроса.
    """
    if last <= 0:
        return []
    return [f"{_ROLE_LABELS.get(m.role, m.role)}: {m.content}" for m in history[-last:]]


def language_rule(question: str) -> str:
    """Язык ответа по исходному вопросу: латиницы больше, чем кириллицы, — английский."""
    en_count = len(re.findall(r"[A-Za-z]", question))
    ru_count = len(re.findall(r"[А-Яа-яЁё]", question))
    return (
        "Отвечай полностью на английском языке."
        if en_count > ru_count
        else "Отвечай полностью на русском языке."
    )


def build_messages(
    question: str,
    history: list[HistoryMessage],
    context: str,
    links: list[tuple[str, str]],
) -> list[dict]:
    """[system, user] для финального ответа (ячейка 27, `answer_question_clean`).

    `question` — исходный вопрос пользователя (не переписанный): по нему выбирается язык, и он же
    стоит в промпте. Пустой контекст превращается в «релевантные материалы не найдены», и
    промпт велит модели честно сказать, что надёжного ответа по материалам нет.
    """
    links_text = (
        "\n".join([f"- {desc}: {url}" for desc, url in links])
        if links
        else "Ссылки не найдены"
    )
    history_text = "\n".join(history_lines(history, PROMPT_HISTORY_MESSAGES))

    prompt = f"""
История текущего диалога:
{history_text or "нет"}

Материалы:
{context or "релевантные материалы не найдены"}

Ссылки:
{links_text or 'релевантных ссылок нет'}

Вопрос пользователя:
{question}

Ответ:
""".strip()

    system = FINAL_SYSTEM + (
        "\nОБЯЗАТЕЛЬНО: " + language_rule(question) +
        " Язык определён по текущему исходному сообщению пользователя. "
        "Историю диалога используй для понимания смысла, но не для выбора языка ответа."
    )

    return [
        {"role": "system", "content": system},
        {"role": "user", "content": prompt},
    ]
